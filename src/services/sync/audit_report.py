def residency_report(central: Path) -> list[dict]:
    """Attention-budget report over the central repository (P2, 2026-11).

    Every installed skill's frontmatter ``description`` rides in the
    agent's system prompt on every message, whether or not the skill is
    used.  This report ranks skills by the context their description
    costs, so over-verbose entries can be trimmed or demoted.

    Token estimates are heuristics - CJK chars count about one token each,
    other scripts about four chars per token.  Good enough for ranking,
    not for billing.
    """
    from ..inventory import list_skills
    from ..spec import DESC_MAX, parse_frontmatter

    rows: list[dict] = []
    for d in list_skills(central):
        md = d / "SKILL.md"
        text = md.read_text(encoding="utf-8", errors="replace")
        fields, _warnings = parse_frontmatter(text)
        desc = fields.get("description", "")
        desc_chars = len(desc)
        cjk = sum(1 for ch in desc if "\u4e00" <= ch <= "\u9fff")
        other = desc_chars - cjk
        desc_tokens = int(cjk + other / 4)
        body_lines = len(text.splitlines())
        dir_kb = round(
            sum(f.stat().st_size for f in d.rglob("*") if f.is_file()) / 1024, 1
        )
        if desc_chars > DESC_MAX:
            suggestion = "over spec limit - trim required"
        elif desc_chars > 400:
            suggestion = "consider trimming"
        elif desc_chars < 20:
            suggestion = "too short - weak trigger"
        else:
            suggestion = "ok"
        rows.append({
            "skill": d.name,
            "desc_chars": desc_chars,
            "desc_tokens_est": desc_tokens,
            "body_lines": body_lines,
            "dir_kb": dir_kb,
            "suggestion": suggestion,
        })
    rows.sort(key=lambda r: r["desc_tokens_est"], reverse=True)
    return rows
