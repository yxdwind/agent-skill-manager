def list_skills() -> list[Path]:
    """List all skills in the central repository (thin wrapper).

    The implementation lives in :mod:`.inventory` so ``spec`` can
    enumerate the central repo without importing the sync engine (the
    spec ⇄ sync module-level cycle found by the 2026-10-31 health
    check). Reading ``CENTRAL_DIR`` through this module (instead of
    letting the inventory default resolve it) keeps the established
    ``patch sync.CENTRAL_DIR`` test seam working for every consumer.

    Returns:
        Sorted list of skill directory paths.
    """
    return _enumerate_skills(_pkg.CENTRAL_DIR)

def print_onboarding() -> None:
    """3-step first-run guidance shown whenever the central repo is empty."""
    print("No skills yet. Get started in 3 steps:")
    print("  1. askill search <keyword>            find skills on skills.sh")
    print("  2. askill install owner/repo@skill    install into the central repo")
    print("  3. askill watch                       auto-sync on every change")
    print()

def get_status(skill_name: str | None = None) -> list[StatusEntryDetail]:
    """Get installation status of skills across all products.

    Args:
        skill_name: If specified, only check this skill.

    Returns:
        List of :class:`StatusEntryDetail` dicts with keys:
        skill_name, product_short, product_name, status, method, plus an
        optional ``reason`` on degraded rows (n/a: no build for the
        current platform).
    """
    skills = list_skills()
    if skill_name:
        skills = [s for s in skills if s.name == skill_name]
        if not skills:
            return []

    results: list[StatusEntryDetail] = []
    for skill_dir in skills:
        # v0.13.0: products sharing the same skill dir (traesolo/traecn,
        # qodercnide/qodercn) reuse the first product's computed status
        # instead of re-checking the identical path again.
        computed: dict[Path, tuple[str, str]] = {}
        for p in _pkg.PRODUCTS:
            entry: StatusEntryDetail = {
                "skill_name": skill_dir.name,
                "product_short": p["short"],
                "product_name": p["name"],
                "status": "",
                "method": p["sync_method"],
            }
            if p["sync_method"] == "native":
                entry["status"] = "ok" if skill_dir.exists() else "missing"
            elif p["sync_method"] == "pack":
                entry["status"] = _pack_status(skill_dir)
            else:
                target = _pkg.get_product_path(p)
                if target is None:
                    # A2 (health check 2026-10-31): carry the reason so
                    # `askill status --json` consumers can tell "not
                    # applicable" apart from "unexplained".
                    entry["status"] = "n/a"
                    entry["reason"] = f"no {_platform_key()} build"
                elif target in computed:
                    entry["status"], entry["method"] = computed[target]
                else:
                    link_path = target / skill_dir.name
                    if link_path.exists() or link_path.is_symlink():
                        if _pkg.is_symlink_or_junction(link_path):
                            entry["status"] = "ok"
                            entry["method"] = "link"
                        else:
                            entry["status"] = "ok"
                            entry["method"] = "copy"
                    else:
                        # BUGFIX 2026-08-14: previously extra_dirs (e.g. AutoClaw's
                        # ~/.openclaw-autoclaw/skills/) were never checked, so a skill
                        # synced only to an extra dir showed "missing". Check them too:
                        # if ANY extra dir has the skill linked/copied, report ok.
                        # The TypedDict field is typed ``list[Path]`` but
                        # ``p.get(...)`` widens to ``object`` because the
                        # key is missing for products that don't ship extras;
                        # the runtime default ``[]`` makes the for-loop safe.
                        extra_dirs = p.get(f"extra_dirs_{_platform_key()}", [])
                        extra_ok = False
                        extra_method = ""
                        for extra in extra_dirs:
                            if extra is None:
                                continue
                            extra_link = Path(extra) / skill_dir.name
                            if extra_link.exists() or extra_link.is_symlink():
                                extra_ok = True
                                extra_method = "link" if _pkg.is_symlink_or_junction(extra_link) else "copy"
                                break
                        if extra_ok:
                            entry["status"] = "ok"
                            entry["method"] = extra_method
                        else:
                            entry["status"] = "missing"
                    computed[target] = (entry["status"], entry["method"])
            results.append(entry)
    return results

def _pack_status(skill_dir: Path) -> str:
    """Status of a skill for pack-mode (DuMate) products.

    ``manual`` - no zip exported yet; ``packed`` - zip exists and is not
    older than SKILL.md; ``stale`` - zip exists but SKILL.md changed after
    it was packed.
    """
    zip_path = _pkg.CENTRAL_DIR / f"{skill_dir.name}.zip"
    if not zip_path.exists():
        return "manual"
    skill_md = skill_dir / "SKILL.md"
    try:
        if not skill_md.exists() or zip_path.stat().st_mtime >= skill_md.stat().st_mtime:
            return "packed"
    except OSError:
        return "packed"
    return "stale"

def sync_skill(
    skill_name: str | None = None,
    verbose: bool = True,
    force: bool = False,
) -> dict[str, list[tuple[str, bool, str]]]:
    """Sync skills from central repo to all products.

    Per skill, the per-product sync runs concurrently via a small thread
    pool (I/O bound: each ``create_link`` is a ``cmd /c mklink`` subprocess
    or an ``os.symlink`` syscall). ``print()`` and the shared-dir dedup
    map are serialised by ``state_lock`` so output stays in order and the
    dedup invariant (one worker per target path) holds.

    Args:
        skill_name: If specified, only sync this skill. None = sync all.
        verbose: Print progress messages.
        force: Overwrite product directories that exist as real dirs and
            differ from the central repo. Without it (v0.13.0 conflict
            protection) such directories are skipped and reported.

    Returns:
        Dict mapping skill_name -> list of (product_short, success, method).
    """
    if not _pkg.CENTRAL_DIR.exists():
        if verbose:
            print(f"Central repository not found: {_pkg.CENTRAL_DIR}")
        return {}

    skills = list_skills()
    if skill_name:
        skills = [s for s in skills if s.name == skill_name]
        if not skills:
            if verbose:
                print(f"Skill not found: {skill_name}")
            return {}

    if not skills:
        if verbose:
            print("No skills to sync.")
            print_onboarding()
        return {}

    if verbose:
        print(f"\nSyncing {len(skills)} skill(s) to {len(_pkg.PRODUCTS)} product(s)...\n")

    # Cap concurrency so a huge PRODUCTS list (or low-RAM CI) doesn't spawn
    # too many simultaneous ``mklink`` subprocesses; 8 is plenty for I/O.
    # ``adopt_from_platform`` may temporarily shrink PRODUCTS to zero via
    # ``_patch_products`` (the source platform is excluded); a worker count
    # of 0 makes ``ThreadPoolExecutor`` raise, so floor at 1 and skip the
    # pool entirely when there is nothing to do.
    max_workers = max(1, min(len(_pkg.PRODUCTS), 8))
    results = {}
    # P0-1: collect products whose settings.json could not be updated
    # (e.g. locked by a running IDE) so we can warn clearly at the end.
    settings_issues: list[tuple[str, str, str]] = []
    for skill_dir in skills:
        if verbose:
            print(f"[{skill_dir.name}]")
        # v0.13.0: products sharing the same skill dir are synced once -
        # the first product in PRODUCTS order does the work, later ones
        # just report the sharing. The map is per-skill (reset below).
        synced_dirs: dict[Path, str] = {}
        state_lock = Lock()
        with ThreadPoolExecutor(max_workers=max_workers) as pool:
            futures = [
                pool.submit(
                    _pkg._sync_one_product,
                    skill_dir, p, force, synced_dirs, state_lock, verbose,
                    settings_issues,
                )
                for p in _pkg.PRODUCTS
            ]
            # Iterate in submission order so the reported sequence matches
            # PRODUCTS (tests assert specific index-based tuples). A worker
            # that raises unexpectedly returns an error tuple instead of
            # discarding the whole skill's results.
            sync_results = []
            for p, f in zip(_pkg.PRODUCTS, futures, strict=True):
                try:
                    sync_results.append(f.result())
                except Exception as e:
                    sync_results.append((p["short"], False, f"error: {e}"))

        # A secondary that reported ``shared->X`` must not claim success
        # when X itself failed (e.g. conflict on a real dir). Propagate the
        # primary's failure so one directory never reports both ways.
        by_short = {s: (ok, m) for s, ok, m in sync_results}
        for i, (s, ok, m) in enumerate(sync_results):
            if ok and isinstance(m, str) and m.startswith("shared->"):
                primary_ok, primary_method = by_short.get(m.split("->", 1)[1], (True, ""))
                if not primary_ok:
                    sync_results[i] = (s, False, primary_method)
        if verbose:
            print()
        results[skill_dir.name] = sync_results

    # P0-1: one clear, aggregated warning instead of a per-product line that
    # is easy to miss. The skill link exists but is NOT enabled in these
    # products - the most common cause is the IDE holding settings.json open.
    if settings_issues:
        locked = [(n, p) for n, p, r in settings_issues if r == "locked"]
        failed = [(n, p) for n, p, r in settings_issues if r == "failed"]
        print()
        print("  ⚠️  settings.json 未能更新 —— 以下产品的 skill 已建立链接但【未被启用】：")
        if locked:
            print("     多半是对应的 IDE 正在运行并锁定了 settings.json（WinError 5）：")
            for name, path in locked:
                print(f"       • {name}  ({path})")
            print("     处理：关闭/重启对应 IDE 后重跑 `askill sync`，或在产品设置里手动开启该 skill。")
        if failed:
            print("     其他写入失败：")
            for name, path in failed:
                print(f"       • {name}  ({path})")

    return results

def _sync_one_product(
    skill_dir: Path,
    p: ProductSpec,
    force: bool,
    synced_dirs: dict[Path, str],
    state_lock: Lock,
    verbose: bool,
    settings_issues: list[tuple[str, str, str]],
) -> tuple[str, bool, str]:
    """Sync one skill to one product. Returns ``(short, success, method)``.

    Designed to run inside a :class:`ThreadPoolExecutor`. Each block that
    touches ``synced_dirs`` or stdout is wrapped in ``state_lock``; the
    actual ``create_link`` calls run lock-free because their target paths
    are unique to this product (or were reserved by the dedup check above).
    """
    if p["sync_method"] == "native":
        with state_lock:
            if verbose:
                print(f"  {p['short']:>10}: ok native (uses central repo)")
        return (p["short"], True, "native")

    if p["sync_method"] == "pack":
        with state_lock:
            if verbose:
                print(f"  {p['short']:>10}: skip (pack mode - run 'askill pack {skill_dir.name}')")
        return (p["short"], False, "pack")

    target = _pkg.get_product_path(p)
    if target is None:
        with state_lock:
            if verbose:
                print(f"  {p['short']:>10}: skip (no {_platform_key()} build)")
        return (p["short"], False, "n/a")

    # Reserve this target for the current product under the lock so a
    # concurrent thread for a sibling product (e.g. traesolo sharing
    # ~/.trae-cn/skills/ with traecn) sees the entry and reports
    # ``shared->traecn`` instead of double-syncing.
    with state_lock:
        if target in synced_dirs:
            primary_short = synced_dirs[target]
            if verbose:
                print(f"  {p['short']:>10}: ok (shares dir with {primary_short})")
            return (p["short"], True, f"shared->{primary_short}")
        synced_dirs[target] = p["short"]

    # A9 guard: only touch extra dirs / settings.json of products
    # that are actually set up on this machine, so syncing on a
    # machine without e.g. Kimi doesn't litter empty config dirs.
    product_set_up = target.exists()
    link_path = target / skill_dir.name
    success, method, message = create_link(skill_dir, link_path, force=force)
    if method == "conflict":
        # data-safety warning: print regardless of verbosity
        with state_lock:
            print(f"  {p['short']:>10}: SKIP conflict - {message}")
        return (p["short"], False, "conflict")
    with state_lock:
        status_icon = "ok" if success else "FAIL"
        if verbose:
            print(f"  {p['short']:>10}: {status_icon} {method}")

    _sync_extra_dirs(skill_dir, p, force, product_set_up, state_lock, verbose)

    # Enable the skill in the product's settings.json (skills-switch
    # schema, confirmed for WorkBuddy and CodeBuddy). Only when the
    # product root already exists - never create config dirs for
    # products that are not installed.
    settings_path = p.get("settings_file")
    if success and settings_path and settings_path.parent.exists():
        # _enable_in_settings writes atomically (tempfile + os.replace); the
        # lock here only keeps output and disk-write contention in order,
        # not data correctness. A "locked"/"failed" result is collected so
        # sync_skill can print one clear, aggregated warning at the end
        # instead of burying it per-product.
        with state_lock:
            enable_result = _enable_in_settings(settings_path, skill_dir.name, verbose=verbose)
        if enable_result != "ok":
            settings_issues.append((p["name"], str(settings_path), enable_result))

    return (p["short"], success, method)

def _sync_extra_dirs(
    skill_dir: Path,
    p: ProductSpec,
    force: bool,
    product_set_up: bool,
    state_lock: Lock,
    verbose: bool,
) -> None:
    """Sync the product's ``extra_dirs_*`` list (e.g. Kimi's ``~/.kimi-code/skills/``)."""
    extra_dirs = p.get(f"extra_dirs_{_platform_key()}", [])
    if extra_dirs and not product_set_up:
        with state_lock:
            if verbose:
                print(f"  {p['short']:>10}: extra skip (product not set up on this machine)")
        return
    for extra in extra_dirs:  # type: ignore[attr-defined]
        if extra is None:
            continue
        extra_link = Path(extra) / skill_dir.name
        # mkdir -p semantics so the link has a parent
        with contextlib.suppress(OSError):
            extra_link.parent.mkdir(parents=True, exist_ok=True)
        ok2, method2, msg2 = create_link(skill_dir, extra_link, force=force)
        with state_lock:
            if ok2:
                if verbose:
                    print(f"  {p['short']:>10}: extra -> {extra_link} ({method2})")
            elif method2 == "conflict":
                # msg2 is the per-extra-dir conflict reason; the previous
                # implementation accidentally used the outer ``message``
                # (from the primary link), so users saw a misleading
                # cause when only the extra dir differed.
                print(f"  {p['short']:>10}: extra SKIP conflict - {msg2}")
            elif verbose:
                print(f"  {p['short']:>10}: extra FAIL ({method2})")

def remove_skill(skill_name: str, verbose: bool = True) -> list[str]:
    """Remove a skill from central repo and all products.

    Args:
        skill_name: Name of the skill to remove.
        verbose: Print progress messages.

    Returns:
        List of locations where the skill was removed.
    """
    skill_dir = _pkg.CENTRAL_DIR / skill_name
    if not skill_dir.exists():
        if verbose:
            print(f"Skill not found in central repo: {skill_name}")
        return []

    removed = []

    for p in _pkg.PRODUCTS:
        if p["sync_method"] in ("native", "pack"):
            continue

        target = _pkg.get_product_path(p)
        if target is None:
            continue

        link_path = target / skill_name
        if link_path.exists() or link_path.is_symlink():
            remove_path(link_path)
            removed.append(p["short"])

        for d in get_all_product_dirs(p)[1:]:
            link_path = d / skill_name
            if link_path.exists() or link_path.is_symlink():
                remove_path(link_path)
                removed.append(f"{p['short']}-alt")

        if (
            p.get("settings_file")
            and p.get("settings_mode") == "skills-switch"
            and _disable_in_settings(p["settings_file"], skill_name)
        ):
            removed.append(f"{p['short']}-settings")

    shutil.rmtree(skill_dir)
    removed.append("central")

    # v0.8.0: drop source-tracking entry as well
    try:
        from ..sources import remove_source
        remove_source(skill_name)
    except Exception:
        pass

    if verbose:
        print(f"Removed '{skill_name}' from: {', '.join(removed)}")
    return removed
